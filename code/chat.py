from argparse import ArgumentParser
import codecs
from datetime import datetime
import json
import locale
import logging
import os
from typing import Any, Dict, List, Union

os.environ['HTTP_PROXY'] = ''
os.environ['HTTPS_PROXY'] = ''
os.environ['SOCKS_PROXY'] = ''
os.environ['NO_PROXY'] = '*'

os.environ['http_proxy'] = ''
os.environ['https_proxy'] = ''
os.environ['socks_proxy'] = ''
os.environ['no_proxy'] = '*'

os.environ['TOKENIZERS_PARALLELISM'] = 'false'
os.environ['PYTORCH_ALLOC_CONF'] = 'expandable_segments:True'
os.environ['VLLM_WORKER_MULTIPROC_METHOD'] = 'spawn'

from nltk.stem.snowball import SnowballStemmer
from openai import OpenAI
from transformers import AutoConfig
from vllm import LLM, SamplingParams

from context_utils.context_utils import (
    format_document_reference,
    graph_element_to_text,
    prepare_context,
    prepare_graph_elements_context,
    prepare_relevant_documents,
)
from dialogue_history_utils.dialogue_history_utils import prepare_dialogue_history
from qa_utils.qa_utils import QA_SYSTEM_PROMPT, prepare_prompt_for_question_answering
from search_utils.search_utils import combine_relevant_chunks
from rerank_utils.rerank_utils import MAX_RERANKER_TOKENS, rerank_documents_with_vllm, rerank_documents_with_api
from rewriting_utils.rewriting_utils import load_abbreviations, prepare_prompt_for_rewriting
from inference_utils.inference_utils import generate_responses_with_vllm, generate_responses_with_api
from vllm_utils.vllm_utils import finalize_vllm


conversation_logger = logging.getLogger(__name__)
RANDOM_SEED: int = 42


def main():
    locale.setlocale(locale.LC_ALL, '')

    parser = ArgumentParser()
    parser.add_argument('-i', '--input', dest='input_name', type=str, required=True,
                        help='The input JSONL knowledge database.')
    parser.add_argument('-r', '--reverse', dest='reverse_index_name', type=str, required=True,
                        help='The input JSON file with prepared reverse chunk index '
                             '(i.e. mapping of the global chunk index to the document index '
                             'and the chunk-in-document index).')
    parser.add_argument('-a', '--abbr', dest='abbreviation_name', type=str, required=True,
                        help='The JSON file with abbreviations and their explanations.')
    parser.add_argument('-o', '--output', dest='output_name', type=str, required=True,
                        help='The output JSONL with completed dialogues.')
    parser.add_argument('--max_words', dest='max_words', type=int, required=False, default=9,
                        help='The maximum number of words in the assistant\'s answer for the dialog history '
                             '(not in the response to the current question).')
    parser.add_argument('--max_input_len', dest='max_input_len', type=int, required=False,
                        default=4096, help='The maximum number of input tokens.')
    parser.add_argument('--max_output_len', dest='max_output_len', type=int, required=False,
                        default=1024, help='The maximum number of output tokens generated by LLM.')
    parser.add_argument('--temperature', dest='temperature', type=float, required=False,
                        default=0.1, help='The inference temperature of the LLM.')
    parser.add_argument('-g', '--graph', dest='graph_dir', type=str, required=True,
                        help='The directory with the RAGU knowledge graph (prepared by prepare_graph_index.py). '
                             'The local (graph neighborhood) and naive (hybrid chunk vector + sparse) '
                             'search modes are the single source of the search candidates.')
    parser.add_argument('--graph_top_k', dest='graph_top_k', type=int, required=False, default=20,
                        help='The maximum number of graph entities for the local search mode.')
    parser.add_argument('--top_k', dest='top_k', type=int, required=False, default=60,
                        help='The maximum number of chunks for the naive search mode '
                             'by one rewritten search query.')
    parser.add_argument('--engine_reranker', dest='engine_reranker_name', type=str, required=False,
                        default='BAAI/bge-reranker-v2-m3',
                        help='The name of the cross-encoder reranker model served by an OpenAI-compatible '
                             'scoring API. It is used inside the RAGU search engines as the first pass '
                             'of the default two-pass reranking scheme. An empty string disables the first '
                             'pass (use it if no scoring service is available).')
    parser.add_argument('--engine_reranker_url', dest='engine_reranker_base_url', type=str, required=False,
                        default=None,
                        help='Your URL prefix for the scoring API of the cross-encoder reranker '
                             '(the "--embedder_url" value is used if it is not specified).')
    parser.add_argument('--engine_reranker_key', dest='engine_reranker_api_key', type=str, required=False,
                        default=None,
                        help='Your secret API key for the scoring API of the cross-encoder reranker '
                             '(the "--embedder_key" value is used if it is not specified).')
    parser.add_argument('--engine_rerank_top_k', dest='engine_rerank_top_k', type=int, required=False, default=30,
                        help='The number of chunks kept by the cross-encoder reranker inside the naive '
                             'search engine (it is ignored if the "--engine_reranker" is not specified).')
    parser.add_argument('--qdrant_location', dest='qdrant_location', type=str, required=False, default='',
                        help='The Qdrant location: an URL of the Qdrant server (it is required for the full '
                             'knowledge graph with entities and relations), ":memory:" for the in-memory '
                             'mode, or an empty string (default) for the local on-disk storage inside the '
                             'graph directory (only the vector-only builds work in this mode, because the '
                             'local on-disk Qdrant supports a single client per folder). The same value '
                             'that was used for the graph building is expected here.')
    parser.add_argument('-e', '--embedder', dest='embedder_name', type=str, required=True,
                        help='The name of the embedding model served by an OpenAI-compatible embeddings API '
                             '(the same model that was used for the graph building).')
    parser.add_argument('--embedder_url', dest='embedder_base_url', type=str, required=False, default=None,
                        help='Your URL prefix for the OpenAI-compatible embeddings API '
                             '(the "--url" value is used if it is not specified).')
    parser.add_argument('--embedder_key', dest='embedder_api_key', type=str, required=False, default=None,
                        help='Your secret OpenAI API key for the embeddings API '
                             '(the "--key" value is used if it is not specified).')
    parser.add_argument('--llm', dest='llm_name', type=str, required=True,
                        help='The name of LLM for reranking, QA and other tasks (it can be Meno, Qwen, Gemma, or '
                             'any other generative LLM).')
    parser.add_argument('--rerank_top_k', dest='rerank_top_k', type=int, required=False, default=12,
                        help='The number of the most relevant pool items (documents and graph elements) '
                             'kept after the LLM-based reranking by one search query.')
    parser.add_argument('--rerank_weight', dest='rerank_weight', type=float, required=False, default=0.8,
                        help='The reranking score weight.')
    parser.add_argument('--min_quality', dest='min_document_quality', type=float, required=False,
                        default=0.0, help='The minimum document quality.')
    parser.add_argument('--gpu', dest='gpu_mem_part', type=float, required=False,
                        default=0.6, help='The GPU memory part for the vLLM-based inference of reranker.')
    parser.add_argument('--num_batched_tokens', dest='num_batched_tokens', type=int, required=False,
                        default=MAX_RERANKER_TOKENS // 2,
                        help='Maximum number of tokens that can be processed in a single iteration '
                             'of the vLLM-based inference.')
    parser.add_argument('--url', dest='openai_base_url', type=str, required=False,
                        default='http://localhost:8000/v1', help='Your URL prefix for OpenAI API calls.')
    parser.add_argument('--key', dest='openai_api_key', type=str, required=False,
                        default='EMPTY', help='Your secret OpenAI API key.')
    parser.add_argument('--vllm', dest='use_vllm', action='store_true',
                        help='Will offline VLLM-based inference be used? '
                             'If not specified, the OpenAI API will be used.')
    args = parser.parse_args()

    if (args.engine_reranker_name is not None) and (len(args.engine_reranker_name.strip()) == 0):
        args.engine_reranker_name = None

    ru_stemmer = SnowballStemmer('russian')

    input_fname = os.path.normpath(args.input_name)
    if not os.path.isfile(input_fname):
        raise IOError(f'The file "{input_fname}" does not exist!')

    abbreviations_fname = os.path.normpath(args.abbreviation_name)
    if not os.path.isfile(abbreviations_fname):
        raise IOError(f'The file "{abbreviations_fname}" does not exist!')

    output_fname = os.path.normpath(args.output_name)
    if not os.path.isfile(output_fname):
        base_output_dir = os.path.dirname(output_fname)
        if len(base_output_dir) > 0:
            if not os.path.isdir(base_output_dir):
                raise IOError(f'The directory "{base_output_dir}" does not exist!')

    mapping_fname = os.path.normpath(args.reverse_index_name)
    if not os.path.isfile(mapping_fname):
        raise IOError(f'The file "{mapping_fname}" does not exist!')

    if args.rerank_weight <= 0.0:
        err_msg = (f'The reranking score weight is too small! '
                   f'Expected a floating-point number greater than 0.0 and less than 1.0, '
                   f'got {args.rerank_weight}.')
        raise ValueError(err_msg)
    if args.rerank_weight >= 1.0:
        err_msg = (f'The reranking score weight is too large! '
                   f'Expected a floating-point number greater than 0.0 and less than 1.0, '
                   f'got {args.rerank_weight}.')
        raise ValueError(err_msg)

    with codecs.open(mapping_fname, mode='r', encoding='utf-8') as fp:
        chunk_reverse_index: Dict[str, Dict[str, int]] = json.load(fp)
    total_num_chunks = len(chunk_reverse_index)
    conversation_logger.info(f'{total_num_chunks} chunks are loaded from the mapping "{mapping_fname}".')
    all_global_indices = sorted(list(map(lambda idx: int(idx), chunk_reverse_index.keys())))
    min_global_index = all_global_indices[0]
    max_global_index = all_global_indices[-1]
    if (min_global_index != 0) or (max_global_index != (total_num_chunks - 1)):
        raise ValueError(f'The chunk mapping "{mapping_fname}" is wrong!')

    with codecs.open(input_fname, mode='r', encoding='utf-8') as fp:
        documents: List[Dict[str, Union[str, float, List[Dict[str, int]]]]] = list(map(
            lambda it3: json.loads(it3),
            filter(
                lambda it2: len(it2) > 0,
                map(lambda it1: it1.strip(), fp.readlines())
            )
        ))
    conversation_logger.info(f'{len(documents)} documents are loaded from the corpus "{input_fname}".')

    graph_dir = os.path.normpath(args.graph_dir)
    if not os.path.isdir(graph_dir):
        raise IOError(f'The directory "{graph_dir}" does not exist!')
    from graph_utils.graph_utils import find_relevant_items_by_graph, load_graph_engines
    embedder_base_url = args.embedder_base_url if args.embedder_base_url is not None else args.openai_base_url
    embedder_api_key = args.embedder_api_key if args.embedder_api_key is not None else args.openai_api_key
    qdrant_location = args.qdrant_location.strip() if len(args.qdrant_location.strip()) > 0 else None
    graph_engines = load_graph_engines(
        graph_dir=graph_dir,
        embedder_name=args.embedder_name,
        embedder_url=embedder_base_url,
        embedder_key=embedder_api_key,
        qdrant_location=qdrant_location,
        engine_reranker_name=args.engine_reranker_name,
        engine_reranker_url=args.engine_reranker_base_url,
        engine_reranker_key=args.engine_reranker_api_key
    )
    conversation_logger.info(f'The RAGU graph search engines are successfully loaded from the "{graph_dir}". '
                             f'There are {len(graph_engines.chunk_to_global)} chunks in the graph mapping.')

    abbreviations = load_abbreviations(abbreviations_fname)
    conversation_logger.info(f'There are {len(abbreviations)} abbreviations.')

    if args.use_vllm:
        client = None
        llm_config = AutoConfig.from_pretrained(args.llm_name)
        sampling_params = SamplingParams(
            temperature=args.temperature,
            max_tokens=args.max_output_len,
            seed=RANDOM_SEED,
            skip_special_tokens=True
        )
        max_model_len = min(args.max_input_len + args.max_output_len, llm_config.max_position_embeddings - 15)
        info_msg = (f'The LLM configuration is loaded from the "{args.llm_name}". '
                    f'The LLM context length is {max_model_len}.')
        conversation_logger.info(info_msg)
        try:
            used_llm = LLM(
                model=args.llm_name,
                gpu_memory_utilization=args.gpu_mem_part,
                max_model_len=MAX_RERANKER_TOKENS,
                max_num_batched_tokens=args.num_batched_tokens,
                enable_chunked_prefill=True,
                tensor_parallel_size=1
            )
        except Exception as err:
            conversation_logger.warning(f'{args.llm_name}: ' + str(err))
            used_llm = LLM(
                model=os.path.normpath(args.llm_name),
                gpu_memory_utilization=args.gpu_mem_part,
                max_model_len=MAX_RERANKER_TOKENS,
                max_num_batched_tokens=args.num_batched_tokens,
                enable_chunked_prefill=True,
                tensor_parallel_size=1
            )
        conversation_logger.info(f'The local LLM is successfully loaded from the "{args.llm_name}".\n')
    else:
        client = OpenAI(
            api_key=args.openai_api_key,
            base_url=args.openai_base_url
        )
        used_llm = args.llm_name
        sampling_params = None

    try:
        source_dialogue_history = []
        with codecs.open(output_fname, mode='a', encoding='utf-8') as out_fp:
            while True:
                user_question = input("Задайте вопрос Менону: ")
                user_question = ' '.join(user_question.strip().split()).strip()
                if user_question.strip().lower() in {'<end>', '<exit>', '<finish>'}:
                    break
                if user_question == '':
                    continue
                prepared_dialogue_history = prepare_dialogue_history(
                    source_dialogue=source_dialogue_history,
                    max_words=args.max_words
                )
                input_messages_for_rewriting = prepare_prompt_for_rewriting(
                    user_question,
                    prepared_dialogue_history,
                    abbreviations,
                    ru_stemmer
                )
                if args.use_vllm:
                    rewritten_ = generate_responses_with_vllm(
                        [input_messages_for_rewriting],
                        used_llm, sampling_params
                    )[0]
                else:
                    rewritten_ = generate_responses_with_api(
                        [input_messages_for_rewriting],
                        client,
                        args.llm_name,
                        args.max_output_len
                    )[0]
                out_fp.write(
                    json.dumps(
                        {
                            'system': input_messages_for_rewriting[0]['content'],
                            'query': input_messages_for_rewriting[-1]['content'],
                            'response': rewritten_,
                            'history': []
                        },
                        ensure_ascii=False
                    ) + '\n'
                )
                search_queries = list(filter(
                    lambda it2: len(it2) > 0,
                    map(lambda it1: it1.strip(), rewritten_.strip().split('\n'))
                ))
                conversation_logger.info(f'"{user_question}": search queries are: {search_queries}.')
                chunk_indices_from_all_queries = []
                graph_items_from_all_queries: Dict[str, Dict[str, Any]] = dict()
                if len(search_queries) > 0:
                    print('\nПереписал ваш вопрос так, чтобы моему поисковому движку легче искалось :-)')
                    if len(search_queries) > 1:
                        if len(search_queries) > 4:
                            info_msg = (f'В результате переписывания получилось аж {len(search_queries)} '
                                        f'простых поисковых запросов! Начинаю поиск по ним.')
                        else:
                            info_msg = (f'В результате переписывания получилось {len(search_queries)} '
                                        f'простых поисковых запроса. Начинаю поиск по ним.')
                        print(info_msg)
                    else:
                        print('Начинаю поиск по переписанному поисковому запросу.')
                    for query_idx, cur_query in enumerate(search_queries):
                        search_pool = find_relevant_items_by_graph(
                            graph_engines=graph_engines,
                            search_query=cur_query,
                            local_top_k=args.graph_top_k,
                            naive_top_k=args.top_k,
                            naive_rerank_top_k=(args.engine_rerank_top_k
                                                if args.engine_reranker_name is not None else None)
                        )
                        pool_chunks = search_pool['chunks']
                        pool_elements = search_pool['entities'] + search_pool['relations']
                        printed_chunks = [(idx, round(score, 3)) for idx, score in pool_chunks]
                        info_msg = (f'"{user_question}" ({query_idx + 1}): the graph search found '
                                    f'{len(search_pool["entities"])} entities, {len(search_pool["relations"])} '
                                    f'relations, and {len(pool_chunks)} unique chunks by the local and naive '
                                    f'modes. The chunks are: {printed_chunks}')
                        conversation_logger.info(info_msg)
                        del printed_chunks
                        if len(pool_chunks) > 0:
                            graph_top_entities = ', '.join(
                                filter(
                                    lambda it: len(it) > 0,
                                    [cur_item['name'] for cur_item in search_pool['entities'][0:5]]
                                )
                            )
                            info_msg = (f'Гибридный поиск по графу знаний ({graph_top_entities}) нашёл '
                                        f'{len(pool_chunks)} текстовых кусочков, {len(search_pool["entities"])} '
                                        f'сущностей и {len(search_pool["relations"])} связей.')
                        else:
                            info_msg = 'Гибридный поиск по графу знаний ничего не нашёл.'
                        print(info_msg)
                        if (len(pool_chunks) == 0) and (len(pool_elements) == 0):
                            info_msg = (f'"{user_question}" ({query_idx + 1}): the search pool is empty.')
                            conversation_logger.info(info_msg)
                            print(f'По запросу "{cur_query}" не нашёл ничего :-(')
                            continue
                        element_document_texts = [graph_element_to_text(cur_item, documents,
                                                                        chunk_reverse_index)
                                                  for cur_item in pool_elements]
                        alpha = args.rerank_weight
                        if args.use_vllm:
                            context_scores = rerank_documents_with_vllm(
                                user_question=user_question,
                                dialogue_history=prepared_dialogue_history,
                                abbr_dict=abbreviations,
                                stemmer=ru_stemmer,
                                global_indices_of_relevant_chunks=[it[0] for it in pool_chunks],
                                documents=documents, chunk_mapping=chunk_reverse_index, llm=used_llm,
                                extra_document_texts=element_document_texts
                            )
                        else:
                            context_scores, samples_for_log = rerank_documents_with_api(
                                user_question=user_question,
                                dialogue_history=prepared_dialogue_history,
                                abbr_dict=abbreviations,
                                stemmer=ru_stemmer,
                                global_indices_of_relevant_chunks=[it[0] for it in pool_chunks],
                                documents=documents, chunk_mapping=chunk_reverse_index, client=client,
                                llm_name=used_llm,
                                extra_document_texts=element_document_texts,
                                log_for_distillation=True
                            )
                            if samples_for_log is not None:
                                for cur_sample in samples_for_log:
                                    out_fp.write(json.dumps(cur_sample, ensure_ascii=False) + '\n')
                                del samples_for_log
                        expected_num_items = len(pool_chunks) + len(pool_elements)
                        if len(context_scores) != expected_num_items:
                            err_msg = (f'The number of items in the search pool does not equal to the number '
                                       f'of relevance scores! {expected_num_items} != {len(context_scores)}.')
                            raise RuntimeError(err_msg)
                        scored_items = []
                        for idx, val in enumerate(pool_chunks):
                            item_score = 0.0
                            if context_scores[idx] > 0.0:
                                item_score = (1.0 - alpha) * val[1] + alpha * context_scores[idx]
                            scored_items.append(({'kind': 'chunk', 'chunk_index': val[0]}, item_score))
                        for offset, cur_item in enumerate(pool_elements):
                            cur_score = context_scores[len(pool_chunks) + offset]
                            item_score = 0.0
                            if cur_score > 0.0:
                                item_score = (1.0 - alpha) * cur_item['score'] + alpha * cur_score
                            scored_items.append(({'kind': 'element', 'item': cur_item}, item_score))
                        ordered_items = list(filter(
                            lambda it3: it3[1] > 0.0,
                            sorted(scored_items, key=lambda it2: (-it2[1], it2[0]['kind'], it2[0].get('chunk_index', 0)))
                        ))
                        if len(ordered_items) > args.rerank_top_k:
                            ordered_items = ordered_items[:args.rerank_top_k]
                        ordered_chunk_indices = [(it[0]['chunk_index'], it[1])
                                                 for it in ordered_items if it[0]['kind'] == 'chunk']
                        num_ordered_elements = len(ordered_items) - len(ordered_chunk_indices)
                        info_msg = (f'"{user_question}" ({query_idx + 1}): quantity of reranked relevant items '
                                    f'is {len(ordered_items)} ({len(ordered_chunk_indices)} chunks and '
                                    f'{num_ordered_elements} graph elements).')
                        conversation_logger.info(info_msg)
                        del scored_items
                        if len(ordered_items) > 0:
                            if len(ordered_chunk_indices) > 0:
                                chunk_indices_from_all_queries = combine_relevant_chunks(
                                    chunk_indices_from_all_queries,
                                    ordered_chunk_indices
                                )
                            for cur_key, cur_score in [(it[0]['item']['key'], it[1])
                                                       for it in ordered_items if it[0]['kind'] == 'element']:
                                cur_stored_item = graph_items_from_all_queries.get(cur_key)
                                if (cur_stored_item is None) or (cur_score > cur_stored_item['score']):
                                    for cur_item in pool_elements:
                                        if cur_item['key'] == cur_key:
                                            graph_items_from_all_queries[cur_key] = {**cur_item, 'score': cur_score}
                                            break
                            info_msg = (f'После переранжирования по запросу "{cur_query}" оставил '
                                        f'{len(ordered_chunk_indices)} текстовых кусочков и '
                                        f'{num_ordered_elements} элементов графа знаний '
                                        f'из {expected_num_items}.')
                        else:
                            info_msg = (f'После переранжирования по запросу "{cur_query}" ничего не оставил. '
                                        f'Всё нерелевантно, увы :-(')
                        print(info_msg)
                        del ordered_items, ordered_chunk_indices, context_scores, search_pool, pool_chunks, \
                            pool_elements, element_document_texts
                else:
                    print('\nНе удалось переписать ваш вопрос так, чтобы мой поисковый движок понял вас :-(')
                info_msg = (f'"{user_question}": quantity of united chunks from all queries is '
                            f'{len(chunk_indices_from_all_queries)}; quantity of united graph elements is '
                            f'{len(graph_items_from_all_queries)}.')
                conversation_logger.info(info_msg)
                prepared_references: List[str] = []
                document_texts = []
                if (len(chunk_indices_from_all_queries) > 0) or (len(graph_items_from_all_queries) > 0):
                    if len(chunk_indices_from_all_queries) > 0:
                        info_msg = 'Ура, поиск в базе знаний завершён! Нашёл '
                        num_found_items = len(chunk_indices_from_all_queries) + len(graph_items_from_all_queries)
                        if num_found_items > 4:
                            info_msg += f'аж {num_found_items}'
                            if info_msg[-2] == '1':
                                info_msg += ' релевантных элементов базы знаний.'
                            else:
                                if info_msg[-1] == '1':
                                    info_msg += ' релевантный элемент базы знаний.'
                                elif info_msg[-1] in {'2', '3', '4'}:
                                    info_msg += ' релевантных элемента базы знаний.'
                                else:
                                    info_msg += ' релевантных элементов базы знаний.'
                        else:
                            info_msg += f'всего лишь {num_found_items}'
                            if info_msg[-1] == '1':
                                info_msg += ' релевантный элемент базы знаний, но не беда! Мал золотник, да дорог :-)'
                            else:
                                info_msg += ' релевантных элемента базы знаний, но не беда! Мал золотник, да дорог :-)'
                        print(info_msg)
                        document_texts, prepared_references = prepare_context(
                            indices_of_relevant_chunks=[it[0] for it in chunk_indices_from_all_queries],
                            scores_of_relevant_chunks=[it[1] for it in chunk_indices_from_all_queries],
                            documents=documents,
                            chunk_mapping=chunk_reverse_index,
                            min_document_quality=args.min_document_quality
                        )
                        if len(chunk_indices_from_all_queries) > 1:
                            if len(document_texts) > 1:
                                info_msg = f'Все эти кусочки взяты из {len(document_texts)}'
                                if info_msg[-2] == '1':
                                    info_msg += ' документов.'
                                else:
                                    if info_msg[-1] == '1':
                                        info_msg += ' документа.'
                                    else:
                                        info_msg += ' документов.'
                            else:
                                info_msg = 'Все эти кусочки взяты из единственного документа.'
                            print(info_msg)
                    else:
                        info_msg = ('Ура, поиск в базе знаний завершён! Текстовые кусочки не найдены, '
                                    'но есть элементы графа знаний.')
                        print(info_msg)
                    print('Теперь думаю над ответом.')
                    graph_items_ordered = sorted(
                        list(graph_items_from_all_queries.values()),
                        key=lambda it: (-it['score'], it['key'])
                    )
                    element_texts, element_source_document_indices = prepare_graph_elements_context(
                        items=graph_items_ordered,
                        documents=documents,
                        chunk_mapping=chunk_reverse_index
                    )
                    referenced_document_indices = set(prepare_relevant_documents(
                        indices_of_relevant_chunks=[it[0] for it in chunk_indices_from_all_queries],
                        scores_of_relevant_chunks=[it[1] for it in chunk_indices_from_all_queries],
                        documents=documents,
                        chunk_mapping=chunk_reverse_index,
                        min_document_quality=args.min_document_quality
                    ).keys())
                    missing_document_indices = element_source_document_indices - referenced_document_indices
                    if len(missing_document_indices) > 0:
                        total_references = len(prepared_references) + len(missing_document_indices)
                        max_number_width = len(f'{total_references}. ')
                        for counter, cur_document_index in enumerate(sorted(missing_document_indices)):
                            cur_number = f'{len(prepared_references) + counter + 1}. '
                            while len(cur_number) < max_number_width:
                                cur_number += ' '
                            prepared_references.append(format_document_reference(
                                document_index=cur_document_index,
                                number=cur_number,
                                max_number_width=max_number_width,
                                documents=documents
                            ))
                    if len(document_texts) > 0:
                        prepared_context = '\n\n'.join(
                            [f'==========\nDOCUMENT {idx + 1}\n==========\n\n{val.strip()}'
                             for idx, val in enumerate(document_texts)]
                        )
                    else:
                        prepared_context = ''
                    if len(element_texts) > 0:
                        graph_context_block = ('**ЭЛЕМЕНТЫ ГРАФА ЗНАНИЙ**\n\n'
                                               + '\n\n'.join(element_texts))
                        prepared_context = (prepared_context + '\n\n' + graph_context_block) \
                            if len(prepared_context) > 0 else graph_context_block
                    prepared_references = '**Дополнительные источники**\n\n' + '\n\n'.join(prepared_references)
                else:
                    prepared_context = ''
                    prepared_references = ''
                    info_msg = ('Искал, искал, но так ничего и не нашёл. Что ж, бывает. '
                                'Буду сочинять ответ своими словами, без опоры на базу знаний.')
                    print(info_msg)
                del chunk_indices_from_all_queries, graph_items_from_all_queries
                qa_user_prompt = prepare_prompt_for_question_answering(
                    user_question=user_question,
                    dialogue_history=prepared_dialogue_history,
                    context=prepared_context,
                    abbr_dict=abbreviations,
                    stemmer=ru_stemmer
                )
                del prepared_dialogue_history, prepared_context
                input_messages_for_qa = [
                    {
                        'role': 'system',
                        'content': QA_SYSTEM_PROMPT.format(
                            current_datetime=datetime.today().strftime('%d %B %Y') + ' года'
                        )
                    }
                ]
                input_messages_for_qa.append({
                    'role': 'user',
                    'content': qa_user_prompt
                })
                if args.use_vllm:
                    final_answer = generate_responses_with_vllm(
                        [input_messages_for_qa],
                        used_llm, sampling_params
                    )[0]
                else:
                    final_answer = generate_responses_with_api(
                        [input_messages_for_qa],
                        client,
                        args.llm_name,
                        args.max_output_len
                    )[0]
                if len(final_answer) > 0:
                    conversation_logger.info(f'"{user_question}": the answer is successfully generated.')
                    print(f'Ура, я нашёл ответ на ваш вопрос! Вот он:\n')
                    print(final_answer + '\n')
                    if len(prepared_references) > 0:
                        print(prepared_references + '\n')
                else:
                    print(f'Не получилось ответить. Видимо, во мне что-то сломалось :-(\n')
                    conversation_logger.warning(f'"{user_question}": the answer is empty.')
                print('\n')
                out_fp.write(
                    json.dumps(
                        {
                            'system': input_messages_for_qa[0]['content'],
                            'query': qa_user_prompt,
                            'response': final_answer,
                            'history': []
                        },
                        ensure_ascii=False
                    ) + '\n'
                )
                source_dialogue_history += [
                    {
                        'role': 'user',
                        'content': user_question
                    },
                    {
                        'role': 'assistant',
                        'content': final_answer
                    }
                ]
                del final_answer, input_messages_for_qa
    finally:
        if args.use_vllm:
            del used_llm
            finalize_vllm()


