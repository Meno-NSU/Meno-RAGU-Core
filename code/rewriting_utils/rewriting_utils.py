def load_abbreviations(src_fname: str) -> Dict[str, Dict[str, Union[str, List[str]]]]:
    with codecs.open(src_fname, mode='r', encoding='utf-8', errors='ignore') as fp:
        src_abbr = json.load(fp)
    prep_abbr = dict()
    for k in src_abbr:
        prep_k = ' '.join(k.strip().split()).strip().lower()
        if isinstance(src_abbr[k], str):
            explanations = [' '.join(src_abbr[k].strip().split()).strip()]
        elif isinstance(src_abbr[k], list):
            explanations = set()
            for val in src_abbr[k]:
                if not isinstance(val, str):
                    raise IOError(f'The file "{src_fname}" contains a wrong record: {k}: {src_abbr[k]}.')
                norm_val = ' '.join(val.strip().split()).strip()
                if len(norm_val) == 0:
                    raise IOError(f'The file "{src_fname}" contains a wrong record: {k}: {src_abbr[k]}.')
                explanations.add(norm_val)
            explanations = sorted(list(explanations))
        else:
            raise IOError(f'The file "{src_fname}" contains a wrong record: {k}: {src_abbr[k]}.')
        if (len(prep_k) == 0) or (len(explanations) == 0):
            raise IOError(f'The file "{src_fname}" contains a wrong record: {k}: {src_abbr[k]}.')
        if prep_k in prep_abbr:
            raise IOError(f'The file "{src_fname}" contains a duplicated abbreviation {k}.')
        prep_abbr[prep_k] = {'abbreviation': k, 'explanation': explanations}
    for k in prep_abbr:
        prep_abbr[k]['explanation'] = sorted(list(prep_abbr[k]['explanation']))
    return prep_abbr


def find_candidates_to_abbreviations(source_text: str, all_abbreviations: Dict[str, Dict[str, Union[str, List[str]]]],
                                     stemmer: Optional[SnowballStemmer] = None) -> str:
    tokens = set(tokenize_and_normalize_text(source_text, stemmer).split())
    selected_abbreviations = set()
    for cur_token in tokens:
        if cur_token in all_abbreviations:
            selected_abbreviations.add(cur_token)
    del tokens
    if stemmer is not None:
        tokens = set(tokenize_and_normalize_text(source_text).split())
        for cur_token in tokens:
            if cur_token in all_abbreviations:
                selected_abbreviations.add(cur_token)
        del tokens
    if len(selected_abbreviations) == 0:
        return ''
    explanation = ''
    for src_abbr in sorted(list(selected_abbreviations)):
        for val in all_abbreviations[src_abbr]['explanation']:
            explanation += f'\n{all_abbreviations[src_abbr]["abbreviation"]} — {val}'
    return explanation.strip()


def prepare_prompt_for_rewriting(cur_question: str, dialogue_history: str,
                                 abbr_dict: Dict[str, Dict[str, Union[str, List[str]]]],
                                 stemmer: Optional[SnowballStemmer] = None,
                                 few_shots: Optional[List[Dict[str, str]]] = None) -> List[Dict[str, str]]:
    prep_question = cur_question.strip()
    if len(prep_question) == 0:
        return []
    messages = [{
        'role': 'system',
        'content': REWRITING_SYSTEM_PROMPT
    }]
    if few_shots is None:
        used_few_shots = FEW_SHOTS
    else:
        used_few_shots = few_shots
    for cur_shot in used_few_shots:
        messages.append({
            'role': 'user',
            'content': cur_shot['input']
        })
        messages.append({
            'role': 'assistant',
            'content': cur_shot['target']
        })
    selected_abbreviations = find_candidates_to_abbreviations(
        cur_question + '\n' + dialogue_history,
        abbr_dict,
        stemmer
    )
    if len(selected_abbreviations) > 0:
        user_prompt = ('ИСТОРИЯ ДИАЛОГА:\n' + dialogue_history.strip() + '\n\nСЛОВАРЬ АББРЕВИАТУР:\n' +
                       selected_abbreviations + '\n\nТЕКУЩИЙ ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n' + prep_question)
    else:
        user_prompt = ('ИСТОРИЯ ДИАЛОГА:\n' + dialogue_history.strip() + '\n\nСЛОВАРЬ АББРЕВИАТУР:' +
                       '\n\nТЕКУЩИЙ ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n' + prep_question)
    messages.append({
        'role': 'user',
        'content': user_prompt
    })
    return messages
